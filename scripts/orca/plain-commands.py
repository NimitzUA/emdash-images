#!/usr/bin/env python3
"""PreToolUse hook for the autonomous Claude roles in an Orca workflow: refuse commands that would
end in an approval prompt nobody is there to answer.

Commands listed in `sandbox.excludedCommands` run outside the Claude sandbox only when the whole
command starts with them. Piped, chained or env-prefixed, they run inside the sandbox and fail,
and the agent then tries workarounds that need the user's approval. The same goes for a retry with
`dangerouslyDisableSandbox`. Refusing early with the reason makes the agent rerun the plain command
or escalate, and nobody is asked. (`sandbox.allowUnsandboxedCommands: false` cannot do this: it
also stops the excluded commands from leaving the sandbox.)

Every refusal goes to the event log (`orca_events.py`), so a run can be audited afterwards.

The excluded commands come from `plain-commands.json` next to this file (generated by orca-setup
from the project's `.orca-setup.json`), each as the list of its leading words.

Files are read, searched, found and written only with the Read, Grep, Glob, Edit and Write tools:
it refuses shell readers and filters (cat, head, tail, sed, awk, grep, rg, find, tee, wc, jq, ...),
inline interpreter code (python3 -c, node -e, perl -pe), and any pipe or redirect, each with the
tool to use instead. Their regex patterns and redirects trip the command checks of Claude Code and
ask the user, who is not watching during a run. For the reviewer and QA roles (`--role=reviewer`,
`--role=qa`) it allows plain read-only git commands (show, log, diff, status, ...) and ls.

It also refuses shell loops, conditions and variable expansions: Claude Code cannot check them in
advance and asks the user, which stalls an unattended role.

It also refuses an in-place edit through sed, perl or awk, which Claude Code asks about when it
cannot parse the expression; the Edit and Write tools never prompt.
"""

import json
import re
import shlex
import sys
from pathlib import Path

CONFIG = json.loads((Path(__file__).with_name("plain-commands.json")).read_text())
TOOLS = tuple(tuple(words) for words in CONFIG["excluded"])
NAMES = ", ".join(" ".join(t) for t in TOOLS)


sys.path.insert(0, str(Path(__file__).resolve().parent))
try:
    from orca_events import record
except ImportError:  # an older checkout without the event log
    def record(*args, **kwargs):
        pass


def deny(reason):
    record("refused", "Bash", tool_input, reason)
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": reason,
        }
    }))
    sys.exit(0)


tool_input = json.load(sys.stdin).get("tool_input", {})
command = tool_input.get("command", "").strip()

if tool_input.get("dangerouslyDisableSandbox"):
    deny(
        f"This role never runs commands outside the sandbox. {NAMES} already run outside it when "
        "the command starts with them. For anything else that the sandbox blocks, stop and escalate."
    )

def outside_single_quotes(command):
    """The command without single-quoted text, which is the only text the shell never expands."""
    out, quote = [], None
    for ch in command:
        if quote:
            if ch == quote:
                quote = None
            elif quote == '"':
                out.append(ch)
        elif ch in "'\"":
            quote = ch
        else:
            out.append(ch)
    return "".join(out)


def command_segments(command):
    """The words of each simple command, and whether a pipe, chain or subshell is present.

    Quoted text is one token, so `;` or `|` inside a JavaScript expression or a message body
    neither counts as a separator nor makes a quoted tool name look like a command. Leading
    `VAR=value` assignments are dropped from each segment.
    """
    lexer = shlex.shlex(command, posix=True, punctuation_chars=True)
    lexer.whitespace_split = True
    segments, current, separated = [], [], False
    for token in lexer:
        if token and set(token) <= set("();<>|&"):
            if token[0] not in "<>":
                separated = True
                segments.append(current)
                current = []
            continue
        if not current and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*=.*", token):
            continue
        current.append(token)
    segments.append(current)
    return [segment for segment in segments if segment], separated


try:
    # A newline outside quotes separates commands like `;`.
    segments, separated = command_segments(re.sub(r"\n", " ; ", command) if "\n" in outside_single_quotes(command) else command)
except ValueError:
    segments, separated = [command.split()], True

# Inline interpreters with quoted code make Claude Code ask the user, who is not watching. Files
# are read with Read and Grep and written with Edit and Write instead.
INTERPRETERS = {"python", "python3", "node", "perl", "ruby"}
if any(
    Path(segment[0]).name in INTERPRETERS
    and any(flag in segment[1:] for flag in ("-c", "-e", "-p", "-pe", "-pi", "--eval"))
    for segment in segments
):
    deny(
        "Do not run inline python, node, perl or ruby code. Read files with the Read tool, search "
        "them with Grep, and change them with Edit or Write (the reviewer rewrites its review file "
        "whole with Write)."
    )

SHELL_KEYWORDS = {"for", "while", "until", "if", "case", "select", "function"}
if any(segment[0] in SHELL_KEYWORDS for segment in segments) or re.search(
    r"\$[A-Za-z_{]", outside_single_quotes(command)
):
    deny(
        "Claude Code cannot check a shell loop, condition or variable expansion in advance, so it "
        "asks the user, who is not watching. Run one plain command per call with literal values "
        "(no for/while/if, no $VAR), and use the Read, Grep and Glob tools to look at files."
    )

substitution = re.search(r"`|\$\(", outside_single_quotes(command))

for tool in TOOLS:
    name = " ".join(tool)
    uses_tool = any(tuple(segment[:len(tool)]) == tool for segment in segments)
    plain = (command == name or command.startswith(f"{name} ")) and not separated and not substitution
    if uses_tool and not plain:
        reason = (
            f"{name} runs outside the sandbox only as a plain command that starts with `{name}`: "
            "no pipe, no `cd ... &&`, no `VAR=value` prefix, no `;`. Inside the sandbox it fails. "
            "Rerun it on its own (run it from the worktree root instead of cd) and read the whole "
            "output."
        )
        if substitution:
            reason += (" A backtick or `$(` inside double quotes runs as a command: put text that "
                       "contains them in single quotes.")
        deny(reason)


def edits_in_place(segment):
    """Whether a simple command rewrites a file in place through sed, perl or awk."""
    program, args = segment[0], segment[1:]
    if program in ("sed", "gsed"):
        return any(re.fullmatch(r"-[A-Za-z]*i.*|--in-place.*", arg) for arg in args)
    if program == "perl":
        return any(re.fullmatch(r"-[A-Za-z]*i.*", arg) for arg in args)
    if program in ("awk", "gawk"):
        return any(a == "-i" and b == "inplace" for a, b in zip(args, args[1:]))
    return False


if CONFIG.get("refuse_in_place_edits", True) and any(edits_in_place(s) for s in segments):
    deny(
        "Edit files with the Edit or Write tool, not an in-place sed, perl or awk: Claude Code asks "
        "the user before an in-place shell edit it cannot fully parse. Files you may not edit stay "
        "unedited either way."
    )


def outside_quotes(command):
    """The command without any quoted text."""
    out, quote = [], None
    for ch in command:
        if quote:
            if ch == quote:
                quote = None
        elif ch in "'\"":
            quote = ch
        else:
            out.append(ch)
    return "".join(out)


# Files are read, searched, found and written only with the Read, Grep, Glob, Edit and Write
# tools. A shell reader's regex, a pipe or a redirect trips the command checks of Claude Code and
# asks the user; across three projects grep alone asked 21 times. The tools never ask.
FILE_UTILITIES = {
    "Read (offset and limit for a part), or Grep with -A/-B/-C": {
        "cat", "head", "tail", "less", "more", "nl", "sed", "awk", "gawk", "cut", "tr"},
    "Grep (-n, -A/-B/-C, glob, output_mode count, head_limit)": {
        "grep", "egrep", "fgrep", "rg", "wc", "sort", "uniq", "jq", "xargs"},
    "Glob": {"find"},
    "Write": {"tee"},
    "`git diff --no-index <a> <b>`": {"diff"},
}
for segment in segments:
    for tool, programs in FILE_UTILITIES.items():
        if Path(segment[0]).name in programs:
            deny(
                f"Do not use `{segment[0]}` on files: use {tool}. Shell readers and filters with "
                "patterns, pipes or redirects make Claude Code ask the user, who is not watching; "
                "the Read, Grep, Glob, Edit and Write tools never ask."
            )

if re.search(r"[|<>]", outside_quotes(command)):
    deny(
        "No pipes or redirects. Run the command plain and read its whole output, or narrow it with "
        "the command's own options (`git log -n 5`, `--json`). Long output belongs in a script's "
        "log under .scratch/, searched with the Grep tool; files are written with Write or Edit."
    )


GIT_READERS = {"show", "log", "diff", "status", "rev-parse", "ls-files", "blame"}


def read_only(segment):
    if segment[0] == "git":
        return len(segment) > 1 and segment[1] in GIT_READERS
    return segment[0] == "ls"


if (
    ("--role=reviewer" in sys.argv or "--role=qa" in sys.argv)
    and segments
    and all(read_only(segment) for segment in segments)
    and not re.search(r"[<>;&`]|\$\(", outside_quotes(command))
):
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "allow",
            "permissionDecisionReason": "Read-only git command for the reviewer or QA.",
        }
    }))
