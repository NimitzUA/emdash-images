#!/usr/bin/env python3
"""PreToolUse hook for the reviewer and QA roles: allow the Write tool only inside the shared run folder.

The reviewer writes its review file into the run folder (`<runs_dir>/<plan>/`) and must not change anything
else. Writing the review through a shell heredoc made Claude Code ask for approval whenever the
text contained a brace next to a quote, and nobody answers prompts during a run. A deny rule
such as `Write(./**)` cannot be used instead: the sandbox turns it into a filesystem deny that
also stops `npm run build` in the worktree. So the reviewer keeps the Write tool and this hook
refuses every path outside the run folder.
"""

import json
import os
import sys
from pathlib import Path

# The run folder comes from plain-commands.json next to this file (generated by orca-setup).
CONFIG = json.loads((Path(__file__).with_name("plain-commands.json")).read_text())
RUNS = os.path.realpath(CONFIG["runs_dir"])

tool_input = json.load(sys.stdin).get("tool_input", {})
path = tool_input.get("file_path") or tool_input.get("notebook_path") or ""

allowed = os.path.isabs(path) and os.path.realpath(path).startswith(RUNS + os.sep)

if not allowed:
    print(json.dumps({
        "hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "permissionDecision": "deny",
            "permissionDecisionReason": (
                "This role writes only its review or QA files, as absolute paths under "
                f"{RUNS}/. Everything else is read-only; report needed changes as findings."
            ),
        }
    }))
sys.exit(0)
